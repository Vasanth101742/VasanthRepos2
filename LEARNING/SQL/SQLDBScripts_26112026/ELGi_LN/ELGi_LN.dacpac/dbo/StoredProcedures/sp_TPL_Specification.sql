CREATE proc sp_TPL_Specification as
begin

insert into TPL_Specification
select * from (
SELECT B.T$REVI,B.T$SLNO,LTRIM(RTRIM(B.T$MITM)) AS MITM,T$WPRE,T$MRAT,
T$RSMM,T$CFAD,
T$MODL,T$PNWD,T$AOPZ,T$TSMM,T$ODWP,T$TTYP,T$DCYC,T$EMAK,T$BACQ,T$ARCP,T$MWPK
FROM 
(SELECT T$MITM,MAX(T$REVI) REVI,MAX(T$SLNO) SLNO FROM TZZSFC001ALL 
GROUP BY T$MITM)A
INNER JOIN TZZSFC001ALL B
ON A.T$MITM=B.T$MITM
AND A.SLNO=B.T$SLNO
AND A.REVI=B.T$REVI
)a

end

GO

